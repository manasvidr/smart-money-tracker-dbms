-- Smart Money Tracker
-- Migration 001: core identity, authorization, and company tables
-- Target: PostgreSQL 15+
--
-- Apply once to an empty project database:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f sql/001_core_tables.sql
--
-- This migration intentionally does not create the remaining domain tables.
-- They will be introduced in dependency order by subsequent migrations.

BEGIN;

CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_username_not_blank CHECK (BTRIM(username) <> ''),
    CONSTRAINT ck_users_email_not_blank CHECK (BTRIM(email) <> ''),
    CONSTRAINT ck_users_password_hash_not_blank CHECK (BTRIM(password_hash) <> '')
);

COMMENT ON TABLE users IS
    'Application accounts. Store a password hash produced by a suitable password-hashing algorithm; never store plaintext passwords.';

CREATE TABLE roles (
    role_id     SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    role_name   VARCHAR(30)  NOT NULL,
    description VARCHAR(255),

    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_role_name UNIQUE (role_name),
    CONSTRAINT ck_roles_role_name_not_blank CHECK (BTRIM(role_name) <> '')
);

COMMENT ON TABLE roles IS
    'Application roles. Initial roles are Admin, Analyst, and Viewer; authorization is enforced by the backend.';

CREATE TABLE user_roles (
    user_id     BIGINT     NOT NULL,
    role_id     SMALLINT   NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id) REFERENCES roles (role_id) ON DELETE CASCADE
);

COMMENT ON TABLE user_roles IS
    'Associative table implementing the many-to-many relationship between users and roles.';

CREATE TABLE companies (
    company_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cik          VARCHAR(10)  NOT NULL,
    ticker       VARCHAR(10)  NOT NULL,
    company_name VARCHAR(255) NOT NULL,
    sector       VARCHAR(100) NOT NULL,
    industry     VARCHAR(100) NOT NULL,

    CONSTRAINT pk_companies PRIMARY KEY (company_id),
    CONSTRAINT uq_companies_cik UNIQUE (cik),
    CONSTRAINT uq_companies_ticker UNIQUE (ticker),
    CONSTRAINT ck_companies_cik_format CHECK (cik ~ '^[0-9]{10}$'),
    CONSTRAINT ck_companies_ticker_format
        CHECK (ticker = UPPER(BTRIM(ticker)) AND ticker ~ '^[A-Z0-9][A-Z0-9.-]{0,9}$'),
    CONSTRAINT ck_companies_name_not_blank CHECK (BTRIM(company_name) <> ''),
    CONSTRAINT ck_companies_sector_not_blank CHECK (BTRIM(sector) <> ''),
    CONSTRAINT ck_companies_industry_not_blank CHECK (BTRIM(industry) <> '')
);

COMMENT ON TABLE companies IS
    'Issuer/company master data. CIK is stored as a zero-padded 10-character SEC identifier. Use the literal Unknown for unavailable sector or industry values; NULL and blank strings are not accepted.';

-- Seed the three approved application roles. This is safe to re-run.
INSERT INTO roles (role_name, description)
VALUES
    ('Admin',   'Full administrative access, including user and role administration.'),
    ('Analyst', 'Access to analytical workflows and permitted data-management operations.'),
    ('Viewer',  'Read-only access to permitted company and dashboard data.')
ON CONFLICT (role_name) DO UPDATE
SET description = EXCLUDED.description;

COMMIT;
